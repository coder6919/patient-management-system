package com.pm.patient_service.model;

import jakarta.persistence.*;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotNull;

import java.time.LocalDate;
import java.util.UUID;

@Entity

public class Patient {

    @Id //unique Id of patients
    @GeneratedValue(strategy = GenerationType.AUTO)
    private UUID id;

    @NotNull //Name of patients
    private String name;

    @NotNull
    @Email
    @Column(unique = true) //Email address for the patient is unique(validation)
    private String email;

    @NotNull
    private String address;

    @NotNull
    private LocalDate dateOfBirth; //save timestamp to persist with DOB

    @NotNull
    private LocalDate registeredDate;

    @NotNull
    private String bloodGroup;


    //Below are getter and setters

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public LocalDate getDateOfBirth() {
        return dateOfBirth;
    }

    public void setDateOfBirth(LocalDate dateOfBirth) {
        this.dateOfBirth = dateOfBirth;
    }

    public LocalDate getRegisteredDate() {
        return registeredDate;
    }

    public void setRegisteredDate(LocalDate registeredDate) {
        this.registeredDate = registeredDate;
    }

    public String getBloodGroup() {
        return bloodGroup;
    }

    public void setBloodGroup(String bloodGroup) {
        this.bloodGroup = bloodGroup;
    }

}
